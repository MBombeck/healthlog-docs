// Postbuild: hash every inline <script> of the built site and write an nginx
// map that holds the hash list, so the Content-Security-Policy in nginx.conf
// can drop 'unsafe-inline' from script-src. Starlight emits the same handful of
// inline scripts on every page, so one list covers the site; it is regenerated
// on every build, so an Astro or Starlight update cannot leave it stale.
// Data blocks (application/ld+json, application/json) are not executed and
// need no hash. The build fails on an inline event handler, which a hash cannot
// allow without 'unsafe-hashes'.
//
// Usage: node scripts/csp-hashes.mjs <dist dir> <output .conf>
import { createHash } from 'node:crypto';
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { join } from 'node:path';

const [distDir, confPath] = process.argv.slice(2);
if (!distDir || !confPath) {
	console.error('usage: csp-hashes.mjs <dist dir> <output .conf>');
	process.exit(1);
}

const DATA_TYPES = new Set(['application/ld+json', 'application/json']);
const SCRIPT = /<script\b([^>]*)>([\s\S]*?)<\/script>/gi;
const HANDLER = /<[a-z][^>]*\son[a-z]+\s*=/i;

async function* htmlFiles(dir) {
	for (const e of await readdir(dir, { withFileTypes: true })) {
		const p = join(dir, e.name);
		if (e.isDirectory()) yield* htmlFiles(p);
		else if (e.name.endsWith('.html')) yield p;
	}
}

const hashes = new Set();
let pages = 0;
for await (const file of htmlFiles(distDir)) {
	const html = await readFile(file, 'utf8');
	if (HANDLER.test(html.replace(SCRIPT, ''))) {
		console.error(`csp-hashes: inline event handler in ${file}`);
		process.exit(1);
	}
	for (const [, attrs, body] of html.matchAll(SCRIPT)) {
		if (/\bsrc\s*=/i.test(attrs)) continue;
		const type = /\btype\s*=\s*["']?([^"'\s>]+)/i.exec(attrs)?.[1]?.toLowerCase();
		if (type && DATA_TYPES.has(type)) continue;
		hashes.add(`'sha256-${createHash('sha256').update(body, 'utf8').digest('base64')}'`);
	}
	pages++;
}

const list = [...hashes].sort().join(' ');
await writeFile(
	confPath,
	`# Generated by scripts/csp-hashes.mjs at build time. Do not edit.\nmap $host $csp_script_hashes {\n    default "${list}";\n}\n`,
);
console.log(`csp-hashes: ${hashes.size} hashes from ${pages} pages -> ${confPath}`);
